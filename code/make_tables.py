#!/usr/bin/env python3
"""Regenerate every table/number used in the paper from the released data. Run from the repository root:
    python code/make_tables.py            # prints and writes results/tables.md
Sections: A bias rates (5 systems), B OPUS-MT controls, C English-specific subset, D French<->Polish, E English-route robustness check.
Annotations of the NLLB, EuroLLM and OPUS-MT control outputs are final (approved by the authors); those of the French-Polish outputs are final (locked 2026-10-22; no native speaker was involved)."""
import csv, io, math, subprocess, sys, contextlib
from itertools import combinations
sys.path.insert(0, 'code')

def rd(f): return list(csv.DictReader(open(f, encoding='utf-8-sig')))
def wilson(k, n, z=1.96):
    p = k/n; d = 1+z*z/n; c = p+z*z/(2*n); h = z*math.sqrt(p*(1-p)/n+z*z/(4*n*n)); return (c-h)/d, (c+h)/d
def cohen_h(p1, p2): return 2*(math.asin(math.sqrt(p1))-math.asin(math.sqrt(p2)))
def mcnemar(a, b):
    n10 = sum(1 for x, y in zip(a, b) if x == 1 and y == 0); n01 = sum(1 for x, y in zip(a, b) if x == 0 and y == 1); n = n10+n01; k = min(n10, n01)
    return n10, n01, (min(1.0, 2*sum(math.comb(n, i) for i in range(k+1))/2**n) if n else 1.0)
out = []
def P(s=''): out.append(s); print(s)

SYS = {  # name -> (ES_EL file, EL_ES file)
 'Google Translate': ('ES_EL_google_translate.csv', 'EL_ES_google_translate.csv'),
 'DeepL Classic': ('ES_EL_deepl_classic.csv', 'EL_ES_deepl_classic.csv'),
 'DeepL Next Gen': ('ES_EL_deepl_nextgen.csv', 'EL_ES_deepl_nextgen.csv'),
 'NLLB-200 1.3B': ('data_nllb/ES_EL_nllb.csv', 'data_nllb/EL_ES_nllb.csv'),
 'EuroLLM-9B': ('data_eurollm/ES_EL_eurollm.csv', 'data_eurollm/EL_ES_eurollm.csv')}
flags = {k: [int(r['Gender_Bias'] or 0) for f in v for r in rd(f)] for k, v in SYS.items()}
P('# Tables regenerated by code/make_tables.py\n'); P('## A. Bias rate (Gender_Bias = 1), 56 sentences per direction\n')
P('| System | ES->EL | EL->ES | Combined (n=112) [95% Wilson] | Cohen h vs Next Gen |'); P('|---|---|---|---|---|')
ng = sum(flags['DeepL Next Gen'])/112
for k, v in flags.items():
    a, b = sum(v[:56]), sum(v[56:]); t = a+b; lo, hi = wilson(t, 112)
    P(f"| {k} | {a}/56 = {a/56:.1%} | {b}/56 = {b/56:.1%} | {t}/112 = {t/112:.1%} [{lo:.1%}-{hi:.1%}] | {'' if k=='DeepL Next Gen' else f'{cohen_h(t/112, ng):.2f}'} |")
P('\nPaired exact McNemar tests on the 112 sentences (only-A / only-B / p):\n')
for a, b in combinations(flags, 2):
    n10, n01, p = mcnemar(flags[a], flags[b]); P(f"- {a} vs {b}: {n10} / {n01} / p = {p:.4f}")

P('\n## B. OPUS-MT controls (bias 1/0, annotator) and gender-marker diagnostic\n')
r = subprocess.run([sys.executable, 'code/summarize_controls.py'], capture_output=True, text=True); P('```\n' + r.stdout.strip() + '\n```')

P('\n## C. English-specific diagnostic subset (number/formality of "you", polysemy)\n')
rows = rd('data_pivot_diagnostic/english_specific_subset.csv'); cols = ['Google', 'DeepL_Classic', 'DeepL_NextGen', 'NLLB', 'EuroLLM', 'OPUS_direct', 'OPUS_EN_cascade', 'OPUS_other_cascade']
for lab, sel in (('ES<->EL (10 sentences)', [x for x in rows if x['Direction'] in ('ES_EL', 'EL_ES')]), ('FR<->PL (3 sentences)', [x for x in rows if x['Direction'] in ('FR_PL', 'PL_FR')])):
    P(f'**{lab}**\n'); P('| System | Matches |'); P('|---|---|')
    for c in cols:
        v = [x[c] for x in sel if x[c] in ('0', '1')]
        if v: P(f"| {c} | {sum(map(int, v))}/{len(v)} |")
    P('')

P('## D. French<->Polish replication (open systems; N sentences not scored)\n')
r = subprocess.run([sys.executable, 'code/analyze_fr_pl.py'], capture_output=True, text=True); P('```\n' + r.stdout.strip() + '\n```')

P('\n## E. English-route robustness check (EuroLLM vs Claude)\n')
import re
N = lambda s: re.sub(r'[\s.!?;¿¡,]+$', '', s.strip()).lower()
for d in ('ES_EL', 'EL_ES'):
    x = rd(f'data_pivot_check/{d}_english_route_eurollm.csv')
    P(f"- {d}: English text identical {sum(N(r['English_EuroLLM'])==N(r['English_Claude']) for r in x)}/{len(x)}; back-translation identical {sum(N(r['BackTrans_EuroLLM'])==N(r['BackTrans_Claude']) for r in x)}/{len(x)}")
P('- Feature-level agreement (judged by the annotator): see data_pivot_check/summary.md')
import os; os.makedirs('results', exist_ok=True); open('results/tables.md', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
